# CLASSIFY ONE QUESTION

def classify_risk_question(
    text,
    label_map,
    hypothesis_template
):
    """
    Classifies one open-ended behavioral response using
    XLM-RoBERTa zero-shot classification.

    Returns:
        {
            'profile': predicted Low / Neutral / High profile,
            'confidence': winning zero-shot score,
            'scores': dictionary containing all three profile scores
        }

    Returns None if the response is missing or non-informative.
    """

    # Missing value
    if pd.isna(text):
        return None

    text = str(text).strip()

    # Empty after cleaning
    if not text:
        return None

    # Detect placeholder/non-informative responses
    if text.lower() in INVALID_TEXT_RESPONSES:
        return None


    # Candidate statements used by XLM-R
    candidate_labels = list(
        label_map.keys()
    )


    # Run zero-shot classification
    result = classifier(
        text,
        candidate_labels,
        hypothesis_template=hypothesis_template,
        multi_label=False
    )


    # Initialize scores for the three final behavioral profiles
    profile_scores = {
        profile: 0.0
        for profile in RISK_PROFILES
    }


    # Convert XLM-R candidate scores into
    # Low / Neutral / High profile scores.
    for label, score in zip(
        result['labels'],
        result['scores']
    ):

        mapped_profile = (
            label_map[label]
        )

        profile_scores[
            mapped_profile
        ] = float(score)


    # Determine the winning profile for this question
    predicted_profile = max(
        profile_scores,
        key=profile_scores.get
    )

    confidence = (
        profile_scores[
            predicted_profile
        ]
    )


    return {
        'profile':
            predicted_profile,

        'confidence':
            confidence,

        'scores':
            profile_scores
    }


# COMBINE Q7 AND Q9

def combine_risk_profiles(
    q7_result,
    q9_result
):
    """
    Combines the independently classified Q7 and Q9 behavioral
    profiles using transparent decision rules.

    IMPORTANT:
    Raw XLM-R probabilities are NOT averaged to determine the
    final behavioral class.

    Rules:

    1. If both questions agree:
       -> use the agreed profile.

    2. If Q7 is Neutral but Q9 is Low/High:
       -> Q9 resolves the classification.

    3. If Q9 is Neutral but Q7 is Low/High:
       -> Q7 resolves the classification.

    4. If one question is Low and the other is High:
       -> classify as Neutral because the behavioral evidence
          directly conflicts.

    5. If only one valid response is available:
       -> use that response.

    6. If neither is usable:
       -> no behavioral profile.
    """

    q7_profile = (
        q7_result['profile']
        if q7_result is not None
        else None
    )

    q9_profile = (
        q9_result['profile']
        if q9_result is not None
        else None
    )


    # No usable behavioral answers

    if (
        q7_profile is None
        and q9_profile is None
    ):

        return (
            np.nan,
            np.nan,
            "No usable Q7 or Q9 response"
        )


    # Only Q7 is available

    if q9_profile is None:

        return (
            q7_profile,
            q7_result['confidence'],
            "Q7 only"
        )


    # Only Q9 is available

    if q7_profile is None:

        return (
            q9_profile,
            q9_result['confidence'],
            "Q9 only"
        )


    # Q7 and Q9 agree

    if q7_profile == q9_profile:

        final_confidence = np.mean([
            q7_result['confidence'],
            q9_result['confidence']
        ])

        return (
            q7_profile,
            final_confidence,
            "Q7 and Q9 agree"
        )


    # Q7 is Neutral
    #
    # Use Q9 because Q9 provides the clearer directional
    # Low/High behavioral evidence.

    if q7_profile == "Neutral":

        return (
            q9_profile,
            q9_result['confidence'],
            "Q9 resolved Neutral Q7"
        )


    # Q9 is Neutral
    #
    # Preserve the respondent's explicit stated risk
    # preference from Q7.

    if q9_profile == "Neutral":

        return (
            q7_profile,
            q7_result['confidence'],
            "Q7 resolved Neutral Q9"
        )


    # Direct Low-vs-High conflict
    #
    # Example:
    # Q7 = Low
    # Q9 = High
    #
    # The behavioral evidence is contradictory, therefore
    # classify the overall respondent as Neutral.
    #
    # We intentionally do NOT assign a numerical confidence
    # because neither classifier predicted Neutral.

    return (
        "Neutral",
        np.nan,
        "Low/High behavioral conflict -> Neutral"
    )


# CLASSIFY ONE RESPONDENT

def classify_behavioral_profile(row):
    """
    Classifies Q7 and Q9 separately, then combines the two
    classifications using the transparent behavioral rules above.
    """

    q7_text = row[
        risk_preference_col
    ]

    q9_text = row[
        loss_reaction_col
    ]


    # QUESTION 7

    q7_result = classify_risk_question(
        q7_text,
        q7_labels,
        "The respondent {}."
    )


    # QUESTION 9

    q9_result = classify_risk_question(
        q9_text,
        q9_labels,
        (
            "After a large investment loss, "
            "the respondent would choose {}."
        )
    )


    # COMBINE THE TWO BEHAVIORAL RESULTS

    (
        final_profile,
        final_confidence,
        decision_basis
    ) = combine_risk_profiles(
        q7_result,
        q9_result
    )


    # Individual question classifications
    q7_profile = (
        q7_result['profile']
        if q7_result is not None
        else np.nan
    )

    q9_profile = (
        q9_result['profile']
        if q9_result is not None
        else np.nan
    )


    # DIAGNOSTIC SCORE AVERAGES

    # We still retain these values because they are useful for
    # researchers inspecting how XLM-R behaved.

    valid_results = [
        result
        for result in [
            q7_result,
            q9_result
        ]
        if result is not None
    ]


    if valid_results:

        diagnostic_scores = {}

        for profile in RISK_PROFILES:

            diagnostic_scores[profile] = np.mean(
                [
                    result['scores'][profile]
                    for result in valid_results
                ]
            )

    else:

        diagnostic_scores = {
            "Low Risk Tolerance": np.nan,
            "Neutral": np.nan,
            "High Risk Tolerance": np.nan
        }


    return pd.Series([
        final_profile,
        final_confidence,

        q7_profile,
        q9_profile,

        diagnostic_scores[
            "Low Risk Tolerance"
        ],

        diagnostic_scores[
            "Neutral"
        ],

        diagnostic_scores[
            "High Risk Tolerance"
        ],

        decision_basis
    ])


