def clean_currency(val, no_means_zero=False):
    """
    Convert common Philippine financial responses into numeric values.

    Missing/unknown responses remain NaN.
    Explicit 'No' may be treated as zero only where logically valid,
    such as the debt question.
    """
    if pd.isna(val):
        return np.nan

    text = str(val).strip().lower()

    if text in ['', 'n/a', 'na', 'none', 'done']:
        return np.nan

    if text == 'no':
        return 0.0 if no_means_zero else np.nan

    text = (
        text.replace(',', '')
            .replace('php', '')
            .replace('₱', '')
            .replace('p', '')
            .replace(' ', '')
    )

    matches = re.findall(r'([\d\.]+)([km]?)', text)

    if not matches:
        return np.nan

    values = []
    global_mult = 1

    if matches[-1][1] == 'k':
        global_mult = 1000
    elif matches[-1][1] == 'm':
        global_mult = 1_000_000

    for num_str, suffix in matches:
        num = float(num_str)

        if suffix == 'k':
            num *= 1000
        elif suffix == 'm':
            num *= 1_000_000
        elif global_mult > 1 and num < 1000:
            num *= global_mult

        values.append(num)

    return max(values)


def clean_age(val):
    """
    Extract plain whole-number values for Age.
    Missing or illogical responses (like 'none') remain NaN.
    """
    if pd.isna(val):
        return np.nan

    text = str(val).strip().lower()

    if text in ['', 'none', 'n/a', 'na']:
        return np.nan

    # Handles "25 years old" -> 25
    match = re.search(r'(\d+)', text)
    if match:
        return int(match.group(1))

    return np.nan


def clean_dependents(val):
    """
    Extract plain whole-number values for Number of Dependents.
    Critically ensures that 'none' or 'zero' are treated as a legitimate 0.
    """
    if pd.isna(val):
        return 0

    text = str(val).strip().lower()

    # For this survey, a blank Number of Dependents is interpreted as having no dependents.
    if text in ['', 'n/a', 'na']:
        return 0

    # Explicitly catch strings that mean 0 dependents
    if text in ['none', 'none.', 'zero', 'no one', 'no']:
        return 0

    number_words = {
        'one': 1, 'two': 2, 'three': 3, 'four': 4, 'five': 5,
        'six': 6, 'seven': 7, 'eight': 8, 'nine': 9, 'ten': 10
    }

    if text in number_words:
        return number_words[text]

    # Handles "0", "2", "3 dependents", etc.
    match = re.search(r'(\d+)', text)
    if match:
        return int(match.group(1))

    return np.nan


