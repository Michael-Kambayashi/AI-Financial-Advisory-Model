# FIND RULE FOR A RESPONDENT

def find_system_rule(
    behavioral_profile,
    financial_capacity,
    market_signal
):

    matches = df_rule_table[
        (
            df_rule_table[
                'Behavioral_Profile'
            ]
            == behavioral_profile
        )
        &
        (
            df_rule_table[
                'Financial_Capacity'
            ]
            == financial_capacity
        )
        &
        (
            df_rule_table[
                'Market_Signal'
            ]
            == market_signal
        )
    ]


    if len(matches) == 1:

        return (
            matches.iloc[0]
            .to_dict()
        )


    return None


# CALCULATE RULE-BASED FEASIBILITY

def calculate_rule_based_feasibility(
    row
):

    behavioral_profile = (
        row[
            'Behavioral_Profile'
        ]
    )

    financial_capacity = (
        row[
            'Financial_Capacity'
        ]
    )

    market_signal = (
        row[
            'Market_Signal'
        ]
    )


    # Missing module output

    if pd.isna(
        behavioral_profile
    ):

        return pd.Series([
            np.nan,
            np.nan,
            'No behavioral profile',
            'No recommendation',
            (
                "Behavioral profile "
                "could not be determined."
            )
        ])


    # Find exact three-variable rule

    matched_rule = (
        find_system_rule(
            behavioral_profile,
            financial_capacity,
            market_signal
        )
    )


    if matched_rule is None:

        explanation = (
            "No matching feasibility "
            "rule was found for: "
            f"{behavioral_profile} + "
            f"{financial_capacity} + "
            f"{market_signal}."
        )

        return pd.Series([
            np.nan,
            np.nan,
            'Rule lookup error',
            'No recommendation',
            explanation
        ])


    # Apply rule delta

    delta = (
        matched_rule[
            'Delta'
        ]
    )


    score = (
        BASELINE_FEASIBILITY
        + delta
    )


    # Keep score within 0–1
    score = max(
        0.0,
        min(
            1.0,
            score
        )
    )


    explanation = (

        f"Behavior: "
        f"{behavioral_profile} | "

        f"Capacity: "
        f"{financial_capacity} | "

        f"Market: "
        f"{market_signal} | "

        f"Rule: "
        f"{matched_rule['System_Rule']} | "

        f"Delta: "
        f"{delta:+.2f}"
    )


    return pd.Series([
        score,
        delta,
        matched_rule[
            'System_Rule'
        ],
        matched_rule[
            'Rule_Result'
        ],
        explanation
    ])


