# DESCRIBE EXTENDED RULES

def describe_extended_rule(
    behavior,
    capacity,
    market,
    delta
):

    key = (
        behavior,
        capacity,
        market
    )


    # Preserve original documented rules

    if key in ORIGINAL_RULE_OVERRIDES:

        return (
            ORIGINAL_RULE_OVERRIDES[
                key
            ]
        )


    # Extended rule terminology

    if delta <= -0.35:

        return (
            'Strongly decrease',
            'Conservative advice'
        )


    elif delta <= -0.20:

        return (
            'Decrease',
            'Defensive advice'
        )


    elif delta < 0:

        return (
            'Slight decrease',
            'Cautious preservation advice'
        )


    elif delta == 0:

        return (
            'Maintain baseline',
            'Balanced advice'
        )


    elif delta <= 0.10:

        return (
            'Restricted increase',
            'Cautious growth advice'
        )


    elif delta <= 0.25:

        return (
            'Slight increase',
            'Accumulation advice'
        )


    else:

        return (
            'Strongly increase',
            'Aggressive advice'
        )


